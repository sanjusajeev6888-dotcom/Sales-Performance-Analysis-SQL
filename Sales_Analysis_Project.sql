WITH monthly_sales AS (
    SELECT
        YEAR(OrderDate) AS year_date,
        MONTH(OrderDate) AS month_date,
        SUM(SalesAmount) AS total_sales
    FROM orders
    GROUP BY YEAR(OrderDate), MONTH(OrderDate)
)
