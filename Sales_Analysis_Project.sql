-- QUERY 41: MONTHLY SALES GROWTH ANALYSIS
-- =====================================================
-- Description:
-- Calculates total sales for each year and month,
-- compares current month sales with the previous month,
-- and calculates the month-over-month sales difference.
with sales_growth as
(select year(orderdate) as year_date,
month(orderdate) as month_date,sum(salesamount) as total_sales
from orders
group by year_date, month_date)
select year_date, month_date, total_sales, 
lag(total_sales) over(order by year_date,month_date) as previous_month_sales,
total_sales - lag(total_sales) over(order by year_date,month_date) as difference
from sales_growth
order by year_date, month_date;

-- QUERY 42: MONTHLY SALES GROWTH PERCENTAGE
-- =====================================================
-- Description:
-- Calculates total sales for each year and month,
-- compares current month sales with the previous month,
-- and calculates the month-over-month sales growth
-- percentage.
WITH sales_growth AS (
    SELECT
        YEAR(OrderDate) AS year_date,
        MONTH(OrderDate) AS month_date,
        SUM(SalesAmount) AS total_sales
    FROM orders
    GROUP BY year_date, month_date
)
SELECT
    year_date,
    month_date,
    total_sales,
    LAG(total_sales) OVER (ORDER BY year_date, month_date) AS previous_month_sales,
    ROUND((total_sales - LAG(total_sales) OVER (
            ORDER BY year_date, month_date))
        / LAG(total_sales) OVER (
            ORDER BY year_date, month_date
        ) * 100,
        2
    ) AS growth_percentage
FROM sales_growth
ORDER BY month_date;

