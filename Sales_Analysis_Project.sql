-- QUERY 52: CATEGORY SALES CONTRIBUTION BY REGION
-- =====================================================
-- Description:
-- Calculates total sales for each category within each
-- region and determines each category's percentage
-- contribution to the overall sales of that region.
WITH region_category_sales AS (
    SELECT
        s.Region,
        c.CategoryName,
        SUM(o.SalesAmount) AS category_sales
    FROM orders o
    JOIN salespersons s
        ON o.SalespersonID = s.SalespersonID
    JOIN products p
        ON o.ProductID = p.ProductID
    JOIN categories c
        ON p.CategoryID = c.CategoryID
    GROUP BY s.Region, c.CategoryID, c.CategoryName
)
SELECT
    Region,
    CategoryName,
    category_sales,
    ROUND(
        category_sales /
        SUM(category_sales) OVER (PARTITION BY Region) * 100,
        2
    ) AS percentage_of_region_sales
FROM region_category_sales
ORDER BY Region, percentage_of_region_sales DESC;

-- QUERY 53: TOP CUSTOMER BY REGION
-- =====================================================
-- Description:
-- Calculates total sales for each customer within
-- each region, ranks customers based on their sales,
-- and identifies the highest-selling customer in
-- each region.
WITH customer_region_sales AS (
    SELECT
        s.Region,
        c.CustomerID,
        c.CustomerName,
        SUM(o.SalesAmount) AS total_sales
    FROM orders o
    JOIN customers c
        ON o.CustomerID = c.CustomerID
    JOIN salespersons s
        ON o.SalespersonID = s.SalespersonID
    GROUP BY
        s.Region,
        c.CustomerID,
        c.CustomerName
),
ranked_customers AS (
    SELECT
        Region,
        CustomerID,
        CustomerName,
        total_sales,
        DENSE_RANK() OVER (
            PARTITION BY Region
            ORDER BY total_sales DESC
        ) AS customer_rank
    FROM customer_region_sales
)
SELECT
    Region,
    CustomerID,
    CustomerName,
    total_sales
FROM ranked_customers
WHERE customer_rank = 1
ORDER BY Region;

-- QUERY 54: HIGHEST-SELLING MONTH
-- =====================================================
-- Description:
-- Calculates total sales for each month and year,
-- ranks the months based on total sales,
-- and identifies the month with the highest sales.
SELECT
    YEAR(OrderDate) AS order_year,
    MONTH(OrderDate) AS order_month,
    SUM(SalesAmount) AS total_sales
FROM orders
GROUP BY YEAR(OrderDate), MONTH(OrderDate)
ORDER BY total_sales DESC
LIMIT 1;

-- QUERY 55: HIGHEST CATEGORY SALES CONTRIBUTION
-- =====================================================
-- Description:
-- Calculates total sales for each product category,
-- determines each category's percentage contribution
-- to overall company sales,
-- and identifies the category with the highest
-- sales contribution percentage.
SELECT
    c.CategoryName,
    SUM(o.SalesAmount) AS category_sales,
    ROUND(
        SUM(o.SalesAmount) /
        (SELECT SUM(SalesAmount) FROM orders) * 100,
        2
    ) AS percentage
FROM orders o
JOIN products p
    ON p.ProductID = o.ProductID
JOIN categories c
    ON p.CategoryID = c.CategoryID
GROUP BY c.CategoryID, c.CategoryName
ORDER BY percentage DESC
LIMIT 1;

-- QUERY 56: MONTHLY SALES GROWTH PERCENTAGE
-- =====================================================
-- Description:
-- Calculates total sales for each year and month,
-- compares current month sales with the previous month,
-- and calculates the month-over-month sales growth
-- percentage.
WITH sales_growth AS (
    SELECT
        YEAR(OrderDate) AS year_date,
        MONTH(OrderDate) AS month_date,
        SUM(SalesAmount) AS total_sales
    FROM orders
    GROUP BY year_date, month_date
)
SELECT
    year_date,
    month_date,
    total_sales,
    LAG(total_sales) OVER (
        ORDER BY year_date, month_date
    ) AS previous_month_sales,
    ROUND(
        (total_sales - LAG(total_sales) OVER (
            ORDER BY year_date, month_date
        ))
        / LAG(total_sales) OVER (
            ORDER BY year_date, month_date
        ) * 100,
        2
    ) AS growth_percentage
FROM sales_growth
ORDER BY year_date, month_date;


