-- QUERY 51: HIGHEST MONTH-OVER-MONTH SALES GROWTH
-- =====================================================
-- Description:
-- Calculates monthly sales growth compared with the
-- previous month and identifies the month with the
-- highest sales growth percentage.
WITH monthly_sales AS (
    SELECT
        YEAR(OrderDate) AS year_date,
        MONTH(OrderDate) AS month_date,
        SUM(SalesAmount) AS total_sales
    FROM orders
    GROUP BY YEAR(OrderDate), MONTH(OrderDate)
),
growth AS (
    SELECT
        year_date,
        month_date,
        total_sales,
        LAG(total_sales) OVER (
            ORDER BY year_date, month_date
        ) AS previous_sales
    FROM monthly_sales
)
SELECT
    year_date,
    month_date,
    ROUND(
        (total_sales - previous_sales) / previous_sales * 100,
        2
    ) AS growth_percentage
FROM growth
WHERE previous_sales IS NOT NULL
ORDER BY growth_percentage DESC
